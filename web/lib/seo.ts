// Stable JSON-LD node ids, so albums, events and projects can point at the one
// Person entity defined on the home page instead of restating it.
export const PERSON_ID = `${SITE_URL}/#person`
export const WEBSITE_ID = `${SITE_URL}/#website`
// Pages other than home don't carry the full Person node, so the reference
// repeats the name Google needs for authors and performers.
export const personRef = { "@type": "Person", "@id": PERSON_ID, name: SITE_NAME, url: SITE_URL }

// Default social-share card (generated by app/opengraph-image.tsx). Pages that
// define their own `openGraph` object must re-include this, since Next replaces
// the whole field rather than deep-merging the file-convention image back in.
export const DEFAULT_OG_IMAGE = "/opengraph-image"

// Build an absolute URL from a site-relative path (or pass through an absolute
// one). Used where Next's metadataBase resolution doesn't apply (sitemap, JSON-LD).
export const absoluteUrl = (path = ""): string => {
  if (/^https?:\/\//.test(path)) return path
  return `${SITE_URL}${path.startsWith("/") ? "" : "/"}${path}`
}

export const DEFAULT_TITLE = "dl Salo — Los Angeles Composer"

// Social cards for local images. Raw /public/images files run 5–10MB, which is
// past Facebook's (8MB) and X's (5MB) limits, so route them through the Next
// image optimiser at card width instead.
export const ogImage = (filename?: string | null): string =>
  filename
    ? `/_next/image?url=${encodeURIComponent(`/images/${filename}`)}&w=1200&q=75`
    : DEFAULT_OG_IMAGE

// Meta description from a CMS post: the hand-written `seo` field, else the
// start of its description text, else the given fallback.
export const describe = (
  post: { seo?: string | null; description?: { document?: unknown } | null } | null | undefined,
  fallback: string,
): string => {
  if (post?.seo) return post.seo
  const text = documentToText(post?.description?.document)
  if (!text) return fallback
  if (text.length <= 155) return text
  return `${text.slice(0, 155).replace(/\s+\S*$/, "")}…`
}

// Per-page metadata. Pages must set openGraph and twitter together: Next
// replaces each object wholesale, so a page that only sets openGraph keeps the
// homepage's twitter title and card.
export const pageMetadata = ({
  title,
  description,
  path,
  image = DEFAULT_OG_IMAGE,
  type = "website",
}: {
  title?: string | null
  description?: string
  path: string
  image?: string
  type?: "website" | "article" | "music.album"
}): Metadata => {
  const socialTitle = title ?? { absolute: DEFAULT_TITLE }
  return {
    ...(title ? { title } : {}),
    ...(description ? { description } : {}),
    alternates: { canonical: path },
    openGraph: { type, url: path, title: socialTitle, description, images: [image] },
    twitter: { card: "summary_large_image", title: socialTitle, description, images: [image] },
  }
}

// schema.org BreadcrumbList for a trail of site-relative links, home first.
export const breadcrumbSchema = (items: { name: string; path: string }[]) => ({
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: [{ name: "Home", path: "/" }, ...items].map((item, i) => ({
    "@type": "ListItem",
    position: i + 1,
    name: item.name,
    item: absoluteUrl(item.path),
  })),
})

// schema.org ItemList of site-relative URLs, for index pages.
export const itemListSchema = (paths: string[]) => ({
  "@context": "https://schema.org",
  "@type": "ItemList",
  itemListElement: paths.map((path, i) => ({
    "@type": "ListItem",
    position: i + 1,
    url: absoluteUrl(path),
  })),
})
